def detect_aem_project_settings(project_path):
    """
    Auto-detect AEM project configuration from the project structure.
    Returns a dict with: aem_app_id, aem_namespace, aem_component_group
    """
    if not project_path or not os.path.exists(project_path):
        return None

    result = {
        'aem_app_id': '',
        'aem_namespace': '',
        'aem_component_group': ''
    }

    try:
        # 1. Detect aem_app_id from ui.apps/src/main/content/jcr_root/apps/ folder structure
        apps_path = os.path.join(project_path, 'ui.apps', 'src', 'main', 'content', 'jcr_root', 'apps')
        if os.path.exists(apps_path):
            # Get first non-system folder (exclude 'acs-commons', 'cq', 'dam', 'wcm', etc.)
            system_folders = {'acs-commons', 'cq', 'dam', 'wcm', 'sling', 'granite', 'libs'}
            app_folders = [f for f in os.listdir(apps_path)
                          if os.path.isdir(os.path.join(apps_path, f))
                          and f not in system_folders
                          and not f.startswith('.')]
            if app_folders:
                result['aem_app_id'] = app_folders[0]

        # 2. Detect aem_namespace from pom.xml or archetype.properties
        # Try archetype.properties first (most reliable)
        archetype_file = os.path.join(project_path, 'archetype.properties')
        if os.path.exists(archetype_file):
            with open(archetype_file, 'r') as f:
                content = f.read()
                # Look for package=com.example.project
                match = re.search(r'package\s*=\s*([a-zA-Z0-9_.]+)', content)
                if match:
                    result['aem_namespace'] = match.group(1).split('.')[-1]  # Get last part

        # Fallback: Try to detect from Java package structure
        if not result['aem_namespace']:
            core_path = os.path.join(project_path, 'core', 'src', 'main', 'java')
            if os.path.exists(core_path):
                # Walk through the first few levels to find the package
                for root, dirs, files in os.walk(core_path):
                    java_files = [f for f in files if f.endswith('.java')]
                    if java_files:
                        # Extract package from first Java file
                        with open(os.path.join(root, java_files[0]), 'r') as f:
                            first_line = f.readline()
                            if 'package' in first_line:
                                match = re.search(r'package\s+([a-zA-Z0-9_.]+)', first_line)
                                if match:
                                    package = match.group(1)
                                    # Extract the main namespace (e.g., com.mohhwebsites.core.models -> mohhwebsites)
                                    parts = package.split('.')
                                    if len(parts) >= 2:
                                        result['aem_namespace'] = parts[1]  # Usually the second part
                        break

        # 3. Detect aem_component_group from existing component .content.xml
        if result['aem_app_id']:
            components_path = os.path.join(apps_path, result['aem_app_id'], 'components')
            if os.path.exists(components_path):
                # Find first component with .content.xml
                for root, dirs, files in os.walk(components_path):
                    if '.content.xml' in files:
                        xml_file = os.path.join(root, '.content.xml')
                        try:
                            with open(xml_file, 'r') as f:
                                content = f.read()
                                # Look for componentGroup="..."
                                match = re.search(r'componentGroup\s*=\s*["\']([^"\']+)["\']', content)
                                if match:
                                    result['aem_component_group'] = match.group(1)
                                    break
                        except:
                            pass
                    if result['aem_component_group']:
                        break

        # Set default component group if not found
        if not result['aem_component_group'] and result['aem_app_id']:
            result['aem_component_group'] = f"{result['aem_app_id'].title()} - Content"

        return result

    except Exception as e:
        st.error(f"Error detecting AEM project settings: {str(e)}")
        return None

