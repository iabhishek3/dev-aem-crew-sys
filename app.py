def create_analysis_documentation(json_path, output_path):
    """
    Create a markdown documentation file from the design analysis JSON.
    This is for user documentation only, not used by agents.
    """
    try:
        import json
        from datetime import datetime

        # Read the JSON file
        with open(json_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Strip markdown code fences if present (CrewAI sometimes wraps JSON in ```json blocks)
        content = content.strip()
        if content.startswith('```json'):
            content = content[7:]  # Remove ```json
        elif content.startswith('```'):
            content = content[3:]  # Remove ```
        if content.endswith('```'):
            content = content[:-3]  # Remove closing ```
        content = content.strip()

        # Parse JSON
        analysis = json.loads(content)

        # Create markdown content
        md_content = f"""# Design Analysis Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

**Source File:** {st.session_state.uploaded_image_path if st.session_state.uploaded_image_path else 'N/A'}

---

## 📦 Component Overview

| Property | Value |
|----------|-------|
| **Name** | `{analysis.get('component', {}).get('name', 'N/A')}` |
| **Type** | `{analysis.get('component', {}).get('type', 'N/A')}` |
| **Width** | `{analysis.get('component', {}).get('width', 'N/A')}` |
| **Height** | `{analysis.get('component', {}).get('height', 'N/A')}` |

---

## 🎨 Color Palette

"""

        # Add colors
        colors = analysis.get('colors', {})
        if colors:
            for color_name, color_value in colors.items():
                md_content += f"- **{color_name.title()}:** `{color_value}` <span style='display:inline-block;width:20px;height:20px;background:{color_value};border:1px solid #ccc;vertical-align:middle;'></span>\n"
        else:
            md_content += "*No colors specified*\n"

        md_content += "\n---\n\n## 📐 Layout Structure\n\n"

        # Add layout
        layout = analysis.get('layout', {})
        if layout:
            md_content += "```css\n"
            for key, value in layout.items():
                md_content += f"{key}: {value};\n"
            md_content += "```\n"
        else:
            md_content += "*No layout specified*\n"

        md_content += "\n---\n\n## 🧩 Elements\n\n"

        # Add elements
        elements = analysis.get('elements', [])
        if elements:
            for idx, element in enumerate(elements, 1):
                element_type = element.get('type', 'unknown')
                md_content += f"### Element {idx}: {element_type.title()}\n\n"

                # Create table for element properties
                md_content += "| Property | Value |\n|----------|-------|\n"
                for key, value in element.items():
                    if key != 'type':
                        # Handle nested objects/arrays
                        if isinstance(value, (dict, list)):
                            value_str = json.dumps(value, indent=2)
                            md_content += f"| **{key}** | `{value_str}` |\n"
                        else:
                            md_content += f"| **{key}** | `{value}` |\n"

                md_content += "\n"
        else:
            md_content += "*No elements specified*\n"

        md_content += """
---

## 📝 Notes

This analysis was automatically generated by the **Visual Strategist** agent.

The JSON specification can be found at: `output-visual_strategist/design_analysis.json`

---

*Generated by AEMplify - Powered by CrewAI & Claude AI*
"""

        # Write markdown file
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(md_content)

        print(f"✅ Successfully wrote markdown documentation to: {output_path}")
        return True

    except json.JSONDecodeError as e:
        print(f"❌ JSON Parse Error: {str(e)}")
        print(f"   Problem parsing JSON at line {e.lineno}, column {e.colno}")
        print(f"   Content preview: {content[:200] if 'content' in locals() else 'N/A'}")
        return False
    except Exception as e:
        print(f"❌ Error creating analysis documentation: {str(e)}")
        import traceback
        traceback.print_exc()
        return False

